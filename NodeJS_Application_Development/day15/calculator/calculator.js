let add = (n1, n2) => {
  return n1 + n2;
};


let subtract = (n1, n2) => {
  return n1 - n2;
};

let divide = (n1, n2) => {
  return n1 / n2;
};

let multiply = (n1, n2) => {
  return n1 * n2;
};

let power = (n1, n2) => {
  return n1 ** n2;
};

export default { add, subtract, divide, multiply, power };
